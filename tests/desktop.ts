const errors: string[] = []
try {
  const page = await app.firstWindow()
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') console.error('renderer:', m.text()) })
  page.on('requestfailed', request => console.error('request failed:', request.url()))
  await page.waitForLoadState('load')
  await expect(page.getByRole('button', { name: '新灵感', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新灵感', exact: true }).click()
  await page.getByRole('textbox', { name: '标题', exact: true }).fill('桌面验收灵感')
  const linked = await page.evaluate(() => window.xm.save({ kind: 'inspiration', title: '链接目标', body: '## 段落\n目标正文' }))
  const markdown = `本机保存验收\n\n[外部链接](https://example.com/test?a=1&b=2)\n\n[本地笔记](${linked.id}.md)\n\n[[链接目标|别名]]\n\n| 标题 | 内容 |\n| :--- | ---: |\n| 表格 | [表格链接](https://example.com) |\n| 双链 | [[链接目标|表格别名]] |`
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await page.getByRole('textbox', { name: 'Markdown 源码' }).fill(markdown)
  await expect(page.getByText('已保存到本地', { exact: true })).toBeVisible()
  const snapshot = await page.evaluate(() => window.xm.snapshot())
  const note = snapshot.notes.find(n => n.title === '桌面验收灵感')!
  expect(note.body).toContain('本机保存验收')
  const file = path.join(snapshot.library, note.path)
  writeFileSync(file, readFileSync(file, 'utf8').replace('本机保存验收', '外部修改回读验收'))
  await expect(page.getByRole('textbox', { name: 'Markdown 源码' })).toContainText('外部修改回读验收', { timeout: 10000 })
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await expect(page.locator('.tiptap table')).toBeVisible()
  await expect(page.locator('.tiptap table tr')).toHaveCount(3)
  await expect(page.getByRole('link', { name: '外部链接', exact: true })).toHaveAttribute('href', 'https://example.com/test?a=1&b=2')
  await expect(page.locator('.tiptap table a')).toHaveAttribute('href', 'https://example.com')
  await expect(page.locator('.tiptap table .wiki-link')).toContainText('表格别名')
  await page.getByRole('link', { name: '本地笔记', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '标题', exact: true })).toHaveValue('链接目标')
  await page.getByRole('heading', { name: '桌面验收灵感' }).click()
  await expect(page.locator('.tiptap table')).toBeVisible()
  await page.locator('.tiptap').click()
  await app.evaluate(async ({ clipboard, nativeImage, ClipboardItem }) => {
    const bitmap = Buffer.alloc(16 * 16 * 4, 255)
    await clipboard.write([new ClipboardItem({ 'image/png': new Blob([new Uint8Array(nativeImage.createFromBitmap(bitmap, { width: 16, height: 16 }).toPNG())], { type: 'image/png' }) })])
  })
  await page.keyboard.press('Control+End')
  await page.keyboard.press('Control+V')
  const localImage = page.locator('.tiptap img.local-image')
  await expect(localImage).toBeVisible()
  await expect.poll(async () => (await page.evaluate(() => window.xm.snapshot())).notes.find(n => n.title === '桌面验收灵感')?.body).toContain('../assets/')
  await localImage.click()
  await page.keyboard.press('Control+C')
  await expect.poll(() => app.evaluate(async ({ clipboard }) => (await clipboard.has('image/png')))).toBe(true)
  await expect.poll(() => app.evaluate(async ({ clipboard }) => (await clipboard.has('text/html')))).toBe(false)
  const copiedImage = await app.evaluate(async ({ clipboard }) => {
    const items = await clipboard.read()
    const image = items.find(item => item.types.includes('image/png'))
    const html = items.find(item => item.types.includes('text/html'))
    return {
      pngSize: image ? (await image.getType('image/png') as Blob).size : 0,
      html: html ? await (await html.getType('text/html') as Blob).text() : ''
    }
  })
  expect(copiedImage.pngSize).toBeGreaterThan(0)
  expect(copiedImage.html).toBe('')
  await page.screenshot({ path: path.join(temporary, 'desktop-editor.png') })
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await expect(page.getByRole('textbox', { name: 'Markdown 源码' })).toContainText('[表格链接](https://example.com)')
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await expect(page.locator('.tiptap table .wiki-link')).toContainText('表格别名')
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await page.getByRole('textbox', { name: 'Markdown 源码' }).fill('立即关闭窗口也应保存')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('立即关闭窗口也应保存')
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible())).toBe(false)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].show())
  await page.getByRole('button', { name: '搜索所有内容' }).click()
  await page.getByPlaceholder('搜索灵感、记忆、选题和候选稿…').fill('关闭窗口')
  await expect(page.getByRole('heading', { name: '桌面验收灵感' })).toBeVisible()
  await page.screenshot({ path: path.join(temporary, 'desktop-search.png') })
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'X 采集', exact: true })).toBeVisible()
  await expect(page.getByLabel('Cookie 导入状态')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '写作模型' })).toHaveCount(0)
  const autostart = page.getByRole('checkbox', { name: '开机时自动启动' })
  await expect(autostart).toBeEnabled()
  await autostart.click()
  await expect.poll(async () => (await page.evaluate(() => window.xm.snapshot())).settings.openAtLogin).toBe(true)
  await expect(autostart).toBeChecked()
  await autostart.click()
  await expect.poll(async () => (await page.evaluate(() => window.xm.snapshot())).settings.openAtLogin).toBe(false)
  await expect(autostart).not.toBeChecked()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: path.join(temporary, 'desktop-dark.png') })
  await page.locator('.sidebar nav').getByRole('button', { name: '灵感' }).click()
  await page.getByRole('button', { name: '桌面验收灵感', exact: true }).click()
  await expect(page.getByRole('button', { name: '创作', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /加入创作素材/ })).toHaveCount(0)
  // Clear formatting: only the selected blocks lose marks and block styles; the unselected bold line keeps its formatting.
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await page.getByRole('textbox', { name: 'Markdown 源码' }).fill('## 格式标题\n\n**加粗** 和 *斜体* 与 [链接](https://example.com) `代码`\n\n> 引用文字\n\n保留 **未选中的加粗**')
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await expect(page.locator('.tiptap h2')).toHaveText('格式标题')
  await page.locator('.tiptap h2').click()
  await page.evaluate(() => {
    const root = document.querySelector('.tiptap')!, start = root.querySelector('h2')!.firstChild!, end = root.querySelector('blockquote p')!.firstChild!
    const range = document.createRange(); range.setStart(start, 0); range.setEnd(end, end.textContent!.length)
    const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range)
  })
  await expect.poll(() => page.evaluate(() => getSelection()!.toString())).toContain('引用文字')
  await page.waitForTimeout(100)
  await page.getByRole('button', { name: '清除格式', exact: true }).click()
  await expect(page.locator('.tiptap h2, .tiptap blockquote, .tiptap a, .tiptap em, .tiptap p > code')).toHaveCount(0)
  await expect(page.locator('.tiptap strong')).toHaveText(['未选中的加粗'])
  await expect.poll(async () => (await page.evaluate(() => window.xm.snapshot())).notes.find(n => n.title === '桌面验收灵感')?.body.trim()).toBe('格式标题\n\n加粗 和 斜体 与 链接 代码\n\n引用文字\n\n保留 **未选中的加粗**')
  // Italic must actually slant Chinese text (fonts have no italic face), in body text and in serif quotes.
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await page.getByRole('textbox', { name: 'Markdown 源码' }).fill('*中文斜体检查*\n\n> *引用斜体检查*')
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  for (const selector of ['.tiptap > p em', '.tiptap blockquote em']) {
    const italic = page.locator(selector)
    await expect(italic).toBeVisible()
    const slanted = await italic.screenshot()
    await italic.evaluate(element => { (element as HTMLElement).style.fontStyle = 'normal' })
    const upright = await italic.screenshot()
    await italic.evaluate(element => { (element as HTMLElement).style.fontStyle = '' })
    expect(slanted.equals(upright), `${selector} 应显示为斜体`).toBe(false)
  }
  // Paste spacing: <br> from HTML and single newlines in pasted Markdown become paragraphs; Shift+Enter still makes a line break.
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await page.getByRole('textbox', { name: 'Markdown 源码' }).fill('开头')
  await page.getByRole('button', { name: '切换 Markdown 源码' }).click()
  await page.locator('.tiptap p', { hasText: '开头' }).click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await app.evaluate(async ({ clipboard, ClipboardItem }) => clipboard.write([new ClipboardItem({ 'text/html': new Blob(['<meta charset="utf-8"><p>网页一<br>网页<strong>二</strong><br><br>网页三</p>'], { type: 'text/html' }), 'text/plain': new Blob(['网页一\n网页二\n\n网页三'], { type: 'text/plain' }) })]))
  await page.keyboard.press('Control+V')
  await expect(page.locator('.tiptap p', { hasText: '网页三' })).toBeVisible()
  await page.keyboard.press('Enter')
  await app.evaluate(async ({ clipboard, ClipboardItem }) => clipboard.write([new ClipboardItem({ 'text/plain': new Blob(['[文档](https://example.com/doc) 第一行\n第二行\n第三行'], { type: 'text/plain' }) })]))
  await page.keyboard.press('Control+V')
  await expect(page.locator('.tiptap p', { hasText: '第三行' })).toBeVisible()
  await page.keyboard.press('Enter')
  await page.keyboard.type('手动一')
  await page.keyboard.press('Shift+Enter')
  await page.keyboard.type('手动二')
  await expect(page.locator('.tiptap br')).toHaveCount(1)
  await expect(page.locator('.tiptap > p')).toHaveText(['开头', '网页一', '网页二', '网页三', '文档 第一行', '第二行', '第三行', '手动一手动二'])
  await expect(page.locator('.tiptap > p strong')).toHaveText('二')
  await expect.poll(async () => (await page.evaluate(() => window.xm.snapshot())).notes.find(n => n.title === '桌面验收灵感')?.body.trim()).toBe('开头\n\n网页一\n\n网页**二**\n\n网页三\n\n[文档](https://example.com/doc) 第一行\n\n第二行\n\n第三行\n\n手动一  \n手动二')
  expect(errors).toEqual([])
  console.log(JSON.stringify({ result: 'PASS', userData, screenshots: temporary, checks: ['Electron 窗口', 'Markdown 保存', '外部编辑回读', '表格渲染', '系统剪贴板粘贴图片', '关闭前保存与托盘隐藏', '中文全局搜索', '无写作模型与创作按钮', '开机自启开关', '深色设置', '清除选中格式', '中文斜体显示', '粘贴换行转段落', '无渲染异常'] }))
} finally { await app.close() }
