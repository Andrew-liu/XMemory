import { _electron as electron, expect, type ElectronApplication } from '@playwright/test'
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const temporary = path.resolve(process.cwd(), '../../trash/xmemeory-dev/memory')
mkdirSync(temporary, { recursive: true })
const userData = mkdtempSync(path.join(temporary, 'profile-'))
const settingsFile = path.join(userData, 'settings.json')
// T-06: illegal values for the new fields fall back to defaults on launch.
writeFileSync(settingsFile, JSON.stringify({ theme: 'light', closeToTray: true, branch: 'main', autoCollect: 'yes', memoryView: 'grid' }))
const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), XMEMEORY_TEST_DATA: userData }
delete env.ELECTRON_RUN_AS_NODE
const launch = () => electron.launch({ ...(process.env.XMEMEORY_TEST_EXE ? { executablePath: process.env.XMEMEORY_TEST_EXE, args: [] } : { args: ['.'] }), env })
const stored = () => JSON.parse(readFileSync(settingsFile, 'utf8'))
let app: ElectronApplication = await launch()
try {
  let page = await app.firstWindow()
  await expect(page.getByRole('heading', { name: '这一周的灵感' })).toBeVisible()
  expect(stored().autoCollect).toBe(false)
  expect(stored().memoryView).toBe('list')
  await page.evaluate(async () => {
    await window.xm.save({ id: 'x-1-11', kind: 'memory', title: 'Alice 的书签', body: '可检索正文甲\n\n![书签图片](../assets/demo.png)\n\n[原文](https://example.com/a/status/11)\n\n> 视频未下载，仅保留封面和原文链接。', author: 'alice', source: 'https://example.com/a/status/11', publishedAt: '2024-02-03T08:30:00.000Z', partial: false })
    await window.xm.save({ id: 'x-1-22', kind: 'memory', title: 'Bob 的书签', body: '可检索正文乙，正文可能不完整，X 未返回完整内容。\n\n[原文](https://example.com/b/status/22)', author: 'bob', source: 'https://example.com/b/status/22', partial: true })
  })
  const nav = (name: string) => page.locator('.sidebar').getByRole('button', { name, exact: true }).or(page.locator('.sidebar nav').getByRole('button', { name })).first()
  await nav('记忆').click()

  // T-08 layout: header holds only the search box; removed controls are gone.
  const header = page.locator('.workspace-header')
  await expect(header.getByLabel('搜索记忆')).toBeVisible()
  await expect(header.getByLabel('搜索记忆')).toHaveAttribute('placeholder', '搜索正文或链接，@作者 按作者搜索')
  await expect(header.getByRole('button', { name: '新灵感' })).toHaveCount(0)
  await expect(header.getByText('让想法有迹可循')).toHaveCount(0)
  for (const label of ['推文链接', '本次上限', '筛选作者', '媒体类型', '列表视图', '卡片视图']) await expect(page.getByLabel(label, { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '采集书签' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '采集', exact: true })).toHaveCount(0)
  const status = page.getByLabel('自动采集状态')
  await expect(status).toHaveText('自动采集未开启')
  await expect(page.locator('.auto-collect').getByRole('button', { name: '开启自动采集' })).toBeVisible()
  await expect(page.getByRole('button', { name: '去开启自动采集' })).toBeVisible()
  await expect(page.locator('.note-card').filter({ hasText: 'Alice 的书签' }).locator('time')).toHaveText('02/03')

  // T-07 in the UI: partial shortcut, @author and combination.
  const search = header.getByLabel('搜索记忆')
  await header.getByRole('button', { name: '1 条不完整' }).click()
  await expect(search).toHaveValue('不完整')
  await expect(header.getByRole('button', { name: '1 条不完整' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Bob 的书签' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alice 的书签' })).toHaveCount(0)
  await search.fill('@ALI')
  await expect(page.getByRole('heading', { name: 'Alice 的书签' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Bob 的书签' })).toHaveCount(0)
  await search.fill('@alice 正文乙')
  await expect(page.locator('.note-card')).toHaveCount(0)
  await search.fill('status/22')
  await expect(page.getByRole('heading', { name: 'Bob 的书签' })).toBeVisible()
  await search.fill('')

  // T-09: recollect only on partial memories.
  await page.getByRole('heading', { name: 'Alice 的书签' }).click()
  await expect(page.getByRole('button', { name: '打开原文' })).toBeVisible()
  await expect(page.getByRole('button', { name: '重新采集' })).toHaveCount(0)
  await expect(page.getByText('视频未下载，仅保留封面和原文链接。', { exact: true })).toBeVisible()
  await page.getByRole('heading', { name: 'Bob 的书签' }).click()
  await expect(page.getByRole('button', { name: '重新采集' })).toBeEnabled()
  await expect(page.getByLabel('不完整记忆补采状态')).toContainText('等待下一轮自动采集')
  await page.getByRole('button', { name: '复制链接' }).click()
  await expect(page.getByText('已复制原文链接')).toBeVisible()
  await page.getByRole('button', { name: '← 返回记忆' }).click()

  // T-05: enabling asks for confirmation; pause and the settings switch are the same state.
  const enable = page.locator('.auto-collect').getByRole('button', { name: '开启自动采集' })
  page.once('dialog', dialog => { expect(dialog.message()).toContain('只在一台电脑上开启'); expect(dialog.message()).toContain('每天最多新增 200 条'); void dialog.dismiss() })
  await enable.click()
  await expect(status).toHaveText('自动采集未开启')
  page.once('dialog', dialog => void dialog.accept())
  await enable.click()
  await expect(status).toContainText('自动采集中 · 下次约')
  await expect(status).toContainText('今日 0/200 · 历史回溯中')
  expect(stored().autoCollect).toBe(true)
  const pause = page.locator('.auto-collect').getByRole('button', { name: '暂停' })
  await expect(pause).not.toHaveClass(/primary/)
  await page.waitForTimeout(400)
  const colors = await pause.evaluate(button => {
    const probe = document.createElement('i'); probe.style.background = 'var(--accent)'; document.body.append(probe)
    const accent = getComputedStyle(probe).backgroundColor; probe.remove()
    return { button: getComputedStyle(button).backgroundColor, accent }
  })
  expect(colors.button).not.toBe(colors.accent)
  await page.screenshot({ path: path.join(temporary, 'desktop-memory-auto.png') })
  await nav('设置').click()
  const runtimeVersion = await page.evaluate(async () => (await window.xm.snapshot()).version)
  await expect(page.getByLabel('当前版本')).toHaveText(`v${runtimeVersion}`)
  if (!process.env.XMEMEORY_TEST_EXE) expect(runtimeVersion).toBe('0.5.6')
  await expect(page.getByRole('button', { name: 'github.com/Andrew-liu/XMemory' })).toBeVisible()
  await expect(page.getByText('这是应用源码仓库，与上方配置的私有数据同步仓库不同。')).toBeVisible()
  const toggle = page.getByLabel('在这台电脑上自动采集书签')
  await expect(toggle).toBeChecked()
  await expect(page.getByText('同一个 X 账号只在一台电脑上开启，多台同时采集会增加风控风险，同步也更容易冲突。', { exact: true })).toBeVisible()
  await expect(page.getByText('每小时采集新书签，每天最多 200 条', { exact: true })).toBeVisible()
  // v0.5.4: X section is a status row; low-frequency Chrome buttons live in the collapsed "高级".
  await expect(page.getByLabel('X 账号状态')).toHaveText('尚未确认登录')
  await expect(page.getByRole('button', { name: '登录 X', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '关闭 CDP Chrome' })).toBeHidden()
  await page.locator('.settings-advanced summary', { hasText: '高级' }).click()
  await expect(page.getByRole('button', { name: '关闭 CDP Chrome' })).toBeVisible()
  await expect(page.getByRole('button', { name: '立即同步' })).toHaveCount(0)
  await expect(page.getByText('Contents 设为 Read and write', { exact: false })).toBeHidden()
  await page.screenshot({ path: path.join(temporary, 'desktop-settings.png'), fullPage: true })
  await app.close()

  app = await launch(); page = await app.firstWindow()
  await nav('记忆').click()
  await expect(page.getByLabel('自动采集状态')).toContainText('自动采集中 · 下次约')
  await page.locator('.auto-collect').getByRole('button', { name: '暂停' }).click()
  await expect(page.getByLabel('自动采集状态')).toHaveText('自动采集未开启')
  expect(stored().autoCollect).toBe(false)
  await nav('设置').click()
  await expect(page.getByLabel('在这台电脑上自动采集书签')).not.toBeChecked()

  // T-10: memory view preference lives in Appearance and persists.
  const views = page.getByRole('group', { name: '记忆视图' })
  await expect(views.getByRole('button', { name: '列表' })).toHaveAttribute('aria-pressed', 'true')
  await views.getByRole('button', { name: '卡片' }).click()
  await expect(views.getByRole('button', { name: '卡片' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByLabel('私有仓库', { exact: true }).fill('https://github.com/example/synthetic-memory.git')
  await page.getByLabel('分支', { exact: true }).fill('master')
  await page.getByRole('button', { name: '保存并检查', exact: true }).click()
  await expect(page.getByLabel('私有仓库', { exact: true })).toHaveValue('example/synthetic-memory')
  await expect(page.getByLabel('分支', { exact: true })).toHaveValue('master')
  await app.close()

  app = await launch(); page = await app.firstWindow()
  await nav('记忆').click()
  await expect(page.getByLabel('自动采集状态')).toHaveText('自动采集未开启')
  await expect(page.locator('.list-scroll.card-grid')).toBeVisible()
  expect(stored().memoryView).toBe('card')
  await page.screenshot({ path: path.join(temporary, 'desktop-memory-card.png') })
  await page.getByRole('button', { name: '去开启自动采集' }).click()
  await expect(page.getByLabel('在这台电脑上自动采集书签')).toBeVisible()
  await page.getByRole('button', { name: '搜索所有内容' }).click()
  await page.getByPlaceholder('搜索灵感、记忆、选题和候选稿…').fill('可检索正文甲')
  await expect(page.getByRole('heading', { name: 'Alice 的书签' })).toBeVisible()
  console.log('PASS: 记忆页布局与搜索框、@作者/不完整搜索、重新采集按钮仅限不完整、开关确认与暂停合一及重启保持、记忆视图偏好持久化、非法设置回退、仓库 URL 保存')
} finally { await app.close().catch(() => {}) }
